// Generates src/components/platform-logos.data.ts from official full-colour marks.
// Sources: svg-logos via @iconify-json/logos (CC0), simple-icons for Snapchat and
// Threads, and icons published on the brands' own sites (public/logos) for
// ShareChat, Moj and Josh. Run: node scripts/build-logos.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const logos = require("@iconify-json/logos/icons.json");
const si = require("simple-icons");

const fromIconify = {
  facebook: "facebook",
  whatsapp: "whatsapp-icon",
  x: "x",
  linkedin: "linkedin-icon",
  telegram: "telegram",
  youtube: "youtube-icon",
  pinterest: "pinterest",
  discord: "discord-icon",
  google_play: "google-play-icon",
  app_store: "apple-app-store",
  apk_site: "android-icon",
};

const out = {};
for (const [platform, name] of Object.entries(fromIconify)) {
  const icon = logos.icons[name];
  if (!icon) throw new Error(`missing ${name}`);
  const w = icon.width ?? logos.width ?? 256;
  const h = icon.height ?? logos.height ?? 256;
  let body = icon.body;
  // X is black-on-white by brand rules; follow the text colour so it also shows on dark themes.
  if (platform === "x") body = body.replace(/fill="#(000|000000)"/gi, 'fill="currentColor"').replace(/<path(?![^>]*fill=)/g, '<path fill="currentColor"');
  out[platform] = { kind: "svg", viewBox: `0 0 ${w} ${h}`, body };
}

// Instagram: the app icon's gradient tile with the white camera outline
// (the collection's "instagram-icon" is the black glyph only).
out.instagram = {
  kind: "svg",
  viewBox: "0 0 24 24",
  body: `<defs><radialGradient id="bs-ig-a" cx="6.4" cy="25.8" r="24" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#FFDD55"/><stop offset=".1" stop-color="#FFDD55"/><stop offset=".5" stop-color="#FF543E"/><stop offset="1" stop-color="#C837AB"/></radialGradient><radialGradient id="bs-ig-b" cx="-4" cy="1.7" r="10.7" gradientTransform="matrix(.2 1 -4.1 .82 3.8 4.3)" gradientUnits="userSpaceOnUse"><stop offset="0" stop-color="#3771C8"/><stop offset=".13" stop-color="#3771C8"/><stop offset="1" stop-color="#6600FF" stop-opacity="0"/></radialGradient></defs><rect width="24" height="24" rx="5.5" fill="url(#bs-ig-a)"/><rect width="24" height="24" rx="5.5" fill="url(#bs-ig-b)"/><g transform="translate(4.2 4.2) scale(.65)"><path fill="#fff" d="${si.siInstagram.path}"/></g>`,
};
// Quora: red app tile with the white Q (the collection only has the wordmark).
out.quora = {
  kind: "svg",
  viewBox: "0 0 24 24",
  body: `<rect width="24" height="24" rx="5.5" fill="#${si.siQuora.hex}"/><g transform="translate(4.8 4.8) scale(.6)"><path fill="#fff" d="${si.siQuora.path}"/></g>`,
};
// Snapchat: yellow tile with the white, black-outlined ghost.
out.snapchat = {
  kind: "svg",
  viewBox: "0 0 24 24",
  body: `<rect width="24" height="24" rx="5.5" fill="#FFFC00"/><g transform="translate(3.6 3.6) scale(.7)"><path d="${si.siSnapchat.path}" fill="#fff" stroke="#000" stroke-width="1.1" stroke-linejoin="round"/></g>`,
};
// Threads: monochrome by brand rules; follows the text colour.
out.threads = { kind: "svg", viewBox: "0 0 24 24", body: `<path fill="currentColor" d="${si.siThreads.path}"/>` };

// Raster icons downloaded from the brands' own websites.
out.sharechat = { kind: "img", src: "/logos/sharechat.png" };
out.moj = { kind: "img", src: "/logos/moj.png" };
out.josh = { kind: "img", src: "/logos/josh.png" };

const header = "// Generated by scripts/build-logos.mjs. Do not edit by hand.\n";
writeFileSync(
  new URL("../src/components/platform-logos.data.ts", import.meta.url),
  `${header}import type { Platform } from "@/lib/types";\n\nexport type LogoData = { kind: "svg"; viewBox: string; body: string } | { kind: "img"; src: string };\n\nexport const LOGOS: Record<Platform, LogoData> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log("wrote", Object.keys(out).length, "logos");
